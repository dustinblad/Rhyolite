/// <summary>
/// Immutable descriptor for one of the 9 flagship design systems from feimacode/open-design-agent-kit.
/// </summary>
public sealed record DesignSystemPreset(
    string Id,
    string Name,
    string Category,
    string Tagline,
    string DesignMdSourcePath,
    bool PrefersDarkByDefault,
    double CardCornerRadius,
    double ButtonCornerRadius,
    DesignSystemPalette LightPalette,
    DesignSystemPalette DarkPalette,
    string UiFontFamily = "SF Pro Text, -apple-system, Helvetica Neue, Segoe UI, Arial, sans-serif",
    string DisplayFontFamily = "SF Pro Display, -apple-system, Helvetica Neue, Segoe UI, Arial, sans-serif",
    string MonoFontFamily = "SF Mono, Menlo, Consolas, Courier New, monospace",
    string SkiaUiFontName = "Helvetica Neue",
    string SkiaDisplayFontName = "Helvetica Neue",
    string SkiaMonoFontName = "Menlo",
    string HeadingFontWeight = "SemiBold",
    string ButtonFontWeight = "SemiBold",
    double ButtonFontSize = 13.0,
    double PrimaryButtonCornerRadius = 980.0,
    double SecondaryButtonCornerRadius = 10.0,
    string PrimaryButtonBorderThickness = "0",
    string SecondaryButtonBorderThickness = "1",
    string ButtonPadding = "15,7",
    string PrimaryButtonBgLightHex = "",
    string PrimaryButtonBgDarkHex = "",
    string PrimaryButtonFgLightHex = "#FFFFFF",
    string PrimaryButtonFgDarkHex = "#FFFFFF",
    string PrimaryButtonBorderLightHex = "#0071E3",
    string PrimaryButtonBorderDarkHex = "#2997FF",
    string PrimaryButtonShadowLight = "0 3 10 0 #330071E3",
    string PrimaryButtonShadowDark = "0 3 12 0 #440071E3",
    string SecondaryButtonShadowLight = "0 1 3 0 #12000000",
    string SecondaryButtonShadowDark = "0 1 4 0 #30000000",
    string CardBorderThickness = "1",
    string CardPadding = "16",
    string CardShadowLight = "0 4 16 0 #12000000",
    string CardShadowDark = "0 6 20 0 #40000000",
    double InputCornerRadius = 10.0,
    string InputBorderThickness = "1",
    double PillCornerRadius = 980.0,
    string PillBorderThickness = "0",
    string ComponentStyleSummary = "980px Capsule Pill Buttons · 14px Gallery Cards · SF Pro Sans")
{
    public string LightAccent => LightPalette.AccentHex;
    public string DarkAccent => DarkPalette.AccentHex;

    public string GetPrimaryButtonBgHex(bool isDarkMode) =>
        isDarkMode
            ? (!string.IsNullOrWhiteSpace(PrimaryButtonBgDarkHex) ? PrimaryButtonBgDarkHex : DarkPalette.AccentHex)
            : (!string.IsNullOrWhiteSpace(PrimaryButtonBgLightHex) ? PrimaryButtonBgLightHex : LightPalette.AccentHex);

    public string GetPrimaryButtonFgHex(bool isDarkMode) => isDarkMode ? PrimaryButtonFgDarkHex : PrimaryButtonFgLightHex;

    public string GetPrimaryButtonBorderHex(bool isDarkMode) => isDarkMode ? PrimaryButtonBorderDarkHex : PrimaryButtonBorderLightHex;

    public string GetPrimaryButtonShadow(bool isDarkMode) => isDarkMode ? PrimaryButtonShadowDark : PrimaryButtonShadowLight;

    public string GetSecondaryButtonShadow(bool isDarkMode) => isDarkMode ? SecondaryButtonShadowDark : SecondaryButtonShadowLight;

    public string GetCardShadow(bool isDarkMode) => isDarkMode ? CardShadowDark : CardShadowLight;

    public DesignSystemPalette GetPalette(bool isDarkMode) => isDarkMode ? DarkPalette : LightPalette;

    public override string ToString() => $"{Name} ({Category})";
}

